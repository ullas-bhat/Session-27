def circular_aperture(
    shape: tuple[int, int], col: float, row: float, radius: float
) -> np.ndarray:
    """Boolean mask of the pixels whose centers lie within a radius.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        shape: Image shape (ny, nx).
        col: Center column in pixels.
        row: Center row in pixels.
        radius: Radius in pixels.

    Returns:
        Boolean mask with the given shape.
    """
    yy, xx = np.indices(shape)
    return np.hypot(xx - col, yy - row) <= radius


def outline_mask(ax, mask: np.ndarray, **kwargs) -> None:
    """Draw the outline of a boolean pixel mask.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        ax: Matplotlib axes holding an image with origin="lower".
        mask: Boolean mask, shape (ny, nx).
        **kwargs: Line properties passed to ax.plot.
    """
    style = {"color": "w", "lw": 1.5}
    style.update(kwargs)
    ny, nx = mask.shape
    for j in range(ny):
        for i in range(nx):
            if not mask[j, i]:
                continue
            if i == 0 or not mask[j, i - 1]:
                ax.plot([i - 0.5, i - 0.5], [j - 0.5, j + 0.5], **style)
            if i == nx - 1 or not mask[j, i + 1]:
                ax.plot([i + 0.5, i + 0.5], [j - 0.5, j + 0.5], **style)
            if j == 0 or not mask[j - 1, i]:
                ax.plot([i - 0.5, i + 0.5], [j - 0.5, j - 0.5], **style)
            if j == ny - 1 or not mask[j + 1, i]:
                ax.plot([i - 0.5, i + 0.5], [j + 0.5, j + 0.5], **style)


def plot_image(
    ax,
    image: np.ndarray,
    star: dict | None = None,
    wide: bool = False,
    mask: np.ndarray | None = None,
    label: str = "flux [e$^-$ s$^{-1}$]",
    **kwargs,
):
    """Show an image with catalog sources and an aperture on top.

    Catalog stars are circles, larger for brighter stars. The target
    is the first catalog entry and is drawn as a cross.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        ax: Matplotlib axes.
        image: Image, shape (ny, nx).
        star: Dictionary from load_star(); if given, its catalog
            positions are overplotted.
        wide: If True use the "wide_src_*" catalog (FFI cutout
            frame) instead of the "src_*" catalog (TPF frame).
        mask: Optional boolean aperture mask to outline.
        label: Colorbar label.
        **kwargs: Passed to ax.imshow.

    Returns:
        The AxesImage from imshow.
    """
    style = {"origin": "lower", "cmap": "viridis"}
    style.update(kwargs)
    im = ax.imshow(image, **style)
    ax.figure.colorbar(im, ax=ax, label=label, fraction=0.046, pad=0.04)
    pre = "wide_src_" if wide else "src_"
    if star is not None and pre + "col" in star:
        col, row = star[pre + "col"], star[pre + "row"]
        tmag = star[pre + "tmag"]
        size = np.clip(30 * 10 ** (-0.25 * (tmag - tmag.min())), 4, 60)
        ax.scatter(col[1:], row[1:], s=size[1:], facecolors="none",
                   edgecolors="r", lw=0.8)
        ax.scatter(col[0], row[0], marker="x", c="r", s=50, lw=1.2)
    if mask is not None:
        outline_mask(ax, mask)
    ax.set_xlim(-0.5, image.shape[1] - 0.5)
    ax.set_ylim(-0.5, image.shape[0] - 0.5)
    ax.set_xlabel("column [pixel]")
    ax.set_ylabel("row [pixel]")
    return im
