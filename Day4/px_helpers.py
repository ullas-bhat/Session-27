def box_model(
    t: np.ndarray, period: float, t0: float, duration: float
) -> np.ndarray:
    """Boolean in-transit mask for a periodic box (as on Tuesday).

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        period: Orbital period in days.
        t0: Mid-transit time in days.
        duration: Transit duration in days.

    Returns:
        Boolean array, True in transit.
    """
    phase = (t - t0 + 0.5 * period) % period - 0.5 * period
    return np.abs(phase) < 0.5 * duration


def inject_transit(
    t: np.ndarray,
    flux: np.ndarray,
    period: float,
    t0: float,
    duration: float,
    depth: float,
) -> np.ndarray:
    """Subtract a box transit from a light curve (as on Tuesday).

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        flux: Relative flux.
        period: Orbital period in days.
        t0: Mid-transit time in days.
        duration: Transit duration in days.
        depth: Transit depth in relative flux.

    Returns:
        New flux array with the transit injected.
    """
    return flux - depth * box_model(t, period, t0, duration)


def transit_duration(
    period: u.Quantity, m_star: u.Quantity, r_star: u.Quantity
) -> u.Quantity:
    """Duration of a central transit on a circular orbit.

    Uses Kepler's third law for a/R_star and T = P / (pi a/R_star).

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        period: Orbital period.
        m_star: Stellar mass.
        r_star: Stellar radius.

    Returns:
        Transit duration in hours.
    """
    a = (const.G * m_star * period**2 / (4 * np.pi**2)) ** (1 / 3)
    return (period / np.pi * r_star / a).to(u.hour)


def measure_depth(
    t: np.ndarray,
    flux: np.ndarray,
    period: float,
    t0: float,
    duration: float,
) -> float:
    """Transit depth from a local fit around each transit.

    Within two durations of each mid-transit time, the flux is fit by
    a quadratic in time plus a box, by linear least squares. The
    quadratic absorbs slow stellar variability; the box coefficient
    is the depth. The result is the mean over transits with data.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        flux: Relative flux.
        period: Orbital period in days.
        t0: Mid-transit time in days.
        duration: Transit duration in days.

    Returns:
        Mean depth in relative flux; NaN if no transit has data.
    """
    dt = (t - t0 + 0.5 * period) % period - 0.5 * period
    epoch = np.round((t - t0) / period).astype(int)
    near = np.abs(dt) < 2.0 * duration
    in_tr = np.abs(dt) < 0.5 * duration
    depths = []
    for e in np.unique(epoch[in_tr]):
        use = near & (epoch == e)
        n_in = (use & in_tr).sum()
        if n_in < 3 or use.sum() - n_in < 8:
            continue
        x = dt[use] / duration
        design = np.vstack([np.ones(x.size), x, x * x,
                            -in_tr[use].astype(float)]).T
        coef = np.linalg.lstsq(design, flux[use], rcond=None)[0]
        depths.append(coef[3])
    return float(np.mean(depths)) if depths else np.nan


