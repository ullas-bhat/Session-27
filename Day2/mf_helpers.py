def pulse_template(
    t: np.ndarray, t0: float = 600.0, width: float = 10.0
) -> np.ndarray:
    """Unit-height Gaussian pulse.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Sample times.
        t0: Pulse center.
        width: Gaussian standard deviation, same units as t.

    Returns:
        Template s(t), with peak value 1.
    """
    return np.exp(-0.5 * ((t - t0) / width) ** 2)


def make_pulse_data(
    inject: bool = True,
    snr: float = 5.0,
    t0: float = 600.0,
    width: float = 10.0,
    n: int = 1000,
    sigma: float = 1.0,
    seed: int = 42,
) -> tuple[np.ndarray, np.ndarray, float]:
    """White noise, optionally with one Gaussian pulse.

    The pulse amplitude is set so that the expected matched-filter
    SNR equals `snr`.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        inject: If True, add the pulse.
        snr: Expected matched-filter SNR of the pulse.
        t0: Pulse center.
        width: Pulse standard deviation in samples.
        n: Number of samples.
        sigma: White-noise standard deviation.
        seed: Random seed.

    Returns:
        Tuple (t, d, sigma).
    """
    rng = np.random.default_rng(seed)
    t = np.arange(n, dtype=float)
    d = rng.normal(0.0, sigma, n)
    if inject:
        s = pulse_template(t, t0, width)
        amp = snr * sigma / np.sqrt(np.sum(s**2))
        d = d + amp * s
    return t, d, sigma


