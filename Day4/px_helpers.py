def matched_filter(
    d: np.ndarray, s: np.ndarray, sigma: np.ndarray | float
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Tuesday's matched filter: fit the amplitude of template s.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        d: Data, shape (n,) or (m, n).
        s: Template, shape (n,).
        sigma: Noise standard deviation, scalar or shape (n,).

    Returns:
        Tuple (a_hat, sigma_a, snr).
    """
    w = 1 / np.asarray(sigma) ** 2 * np.ones_like(s, dtype=float)
    norm = np.sum(w * s * s, axis=-1)
    a_hat = np.sum(w * s * d, axis=-1) / norm
    sigma_a = 1 / np.sqrt(norm)
    return a_hat, sigma_a, a_hat / sigma_a


def harmonics(t: np.ndarray, period: float, n_harm: int) -> np.ndarray:
    """Sine and cosine regressors at a period and its harmonics.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        period: Fundamental period in days.
        n_harm: Number of harmonics, including the fundamental.

    Returns:
        Array with shape (2 * n_harm, n_time).
    """
    rows = []
    for k in range(1, n_harm + 1):
        arg = 2 * np.pi * k * (t - t[0]) / period
        rows += [np.sin(arg), np.cos(arg)]
    return np.array(rows)


def fold_stats(
    phase: np.ndarray, flux: np.ndarray, n_bins: int = 25
) -> tuple[float, float]:
    """Amplitude of a folded light curve and the scatter around it.

    The binned, folded light curve is used as a template (Tuesday,
    Problem 4). The amplitude is its peak-to-peak range; the scatter
    is the standard deviation of the data about it.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        phase: Phases in [-0.5, 0.5).
        flux: Relative flux.
        n_bins: Number of phase bins.

    Returns:
        Tuple (peak-to-peak amplitude, scatter about the fold).
    """
    centers, mean, _ = bin_phase(phase, flux, n_bins)
    good = np.isfinite(mean)
    template = np.interp(phase, centers[good], mean[good], period=1.0)
    amp = float(np.max(mean[good]) - np.min(mean[good]))
    return amp, float(np.std(flux - template))


def gaussian_prf(
    shape: tuple[int, int], col: float, row: float, sigma: float = 0.8
) -> np.ndarray:
    """Pixel-integrated circular Gaussian, normalized to unit flux.

    A crude stand-in for the TESS pixel response function.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        shape: Image shape (ny, nx).
        col: Source column in pixels.
        row: Source row in pixels.
        sigma: Gaussian standard deviation in pixels.

    Returns:
        Image with the given shape; sums to at most 1.
    """
    ny, nx = shape
    xe = (np.arange(nx + 1) - 0.5 - col) / (np.sqrt(2) * sigma)
    ye = (np.arange(ny + 1) - 0.5 - row) / (np.sqrt(2) * sigma)
    ex = 0.5 * np.diff(erf(xe))
    ey = 0.5 * np.diff(erf(ye))
    return ey[:, None] * ex[None, :]


