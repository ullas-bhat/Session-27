def _find(fname: str) -> tuple[str, bool]:
    """Locate a packaged file, falling back to the stand-in copy.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        fname: File name, e.g. "target.npz".

    Returns:
        Tuple (path, is_standin).

    Raises:
        FileNotFoundError: If neither copy exists.
    """
    real = os.path.join(DATA_DIR, fname)
    if os.path.exists(real):
        return real, False
    standin = os.path.join(STANDIN_DIR, fname)
    if os.path.exists(standin):
        warnings.warn(
            f"{real} not found. Loading the SIMULATED stand-in "
            f"{standin}, not TESS data.",
            stacklevel=3,
        )
        return standin, True
    raise FileNotFoundError(
        f"Neither {real} nor {standin} exists. Run "
        "make_standin_data.py or package_thursday_data.py."
    )


def load_star(name: str = "target") -> dict:
    """Load everything we have for one star.

    Every star, including the three unlabeled ones in Problem VIIIb,
    comes back with the same keys. See DATA_CONTRACT.md.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        name: One of "target", "star_A", "star_B", "star_C", or the
            stem of any other bundle written by save_star().

    Returns:
        Dictionary of numpy arrays and scalars. Fluxes are in
        electrons per second, times in days (BTJD), pixel positions
        are zero-indexed (column, row) in the frame of the array
        they describe.
    """
    path, is_standin = _find(f"{name}.npz")
    star = {}
    with np.load(path, allow_pickle=False) as f:
        for key in f.files:
            val = f[key]
            star[key] = val.item() if val.ndim == 0 else val
    for key in ("tpf", "wide", "nbr_flux"):
        if key in star:
            star[key] = star[key].astype(np.float64)
    star["is_standin"] = bool(is_standin or star.get("is_standin", 0))
    return star


def save_star(path: str, **arrays) -> None:
    """Write one star bundle in the format load_star() expects.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        path: Output .npz path.
        **arrays: Keys from DATA_CONTRACT.md. "time" and "sap" are
            required; everything else is optional, and a dashboard
            should skip the panels it has no data for.

    Raises:
        KeyError: If a required key is missing.
        ValueError: If an array length disagrees with "time".
    """
    for key in REQUIRED_KEYS:
        if key not in arrays:
            raise KeyError(f"bundle needs '{key}'")
    n_t = len(arrays["time"])
    for key in ("sap", "sap_err", "pdcsap", "cbv_flux"):
        if key in arrays and len(arrays[key]) != n_t:
            raise ValueError(f"'{key}' must have length {n_t}")
    for key in ("tpf",):
        if key in arrays and arrays[key].shape[0] != n_t:
            raise ValueError(f"'{key}' must have shape ({n_t}, ny, nx)")
    for key in ("nbr_flux", "cbvs"):
        if key in arrays and arrays[key].shape[1] != n_t:
            raise ValueError(f"'{key}' must have shape (n, {n_t})")
    out = {}
    for key, val in arrays.items():
        val = np.asarray(val)
        if key in ("tpf", "wide", "nbr_flux"):
            val = val.astype(np.float32)
        out[key] = val
    np.savez_compressed(path, **out)


def load_cube(name: str = "orion_cube") -> dict:
    """Load an FFI cutout cube for the Challenge Problem.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        name: Stem of the .npz file.

    Returns:
        Dictionary with "time" (n_t,), "cube" (n_t, ny, nx) in
        electrons per second with the per-frame median removed, and
        the catalog arrays "src_col", "src_row", "src_tmag",
        "src_ticid".
    """
    path, is_standin = _find(f"{name}.npz")
    cube = {}
    with np.load(path, allow_pickle=False) as f:
        for key in f.files:
            val = f[key]
            cube[key] = val.item() if val.ndim == 0 else val
    cube["cube"] = cube["cube"].astype(np.float64)
    cube["is_standin"] = bool(is_standin or cube.get("is_standin", 0))
    return cube


def describe(star: dict) -> str:
    """One-paragraph summary of a star bundle.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        star: Dictionary from load_star().

    Returns:
        Human-readable summary of what the bundle holds.
    """
    t = star["time"]
    cadence = (np.median(np.diff(t)) * u.day).to(u.min)
    lines = [
        f"{star.get('name', '?')}: T = {star.get('tmag', np.nan):.1f} "
        f"mag, claimed period {star.get('period', np.nan):.4f} d, "
        f"t0 = {star.get('t0', np.nan):.4f} (flux minimum)",
        f"  {t.size} cadences over {np.ptp(t):.1f} d, "
        f"cadence {cadence.value:.1f} min",
    ]
    for key in ("tpf", "nbr_flux", "cbvs", "wide"):
        if key in star:
            lines.append(f"  {key}: shape {star[key].shape}")
    if star.get("is_standin", False):
        lines.append("  SIMULATED stand-in, not TESS data")
    return "\n".join(lines)


