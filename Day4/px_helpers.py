def fold(t: np.ndarray, period: float, t0: float) -> np.ndarray:
    """Phase in [-0.5, 0.5), with phase 0 at t0.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        period: Period in days.
        t0: Reference epoch in days.

    Returns:
        Phase of each time.
    """
    return ((t - t0) / period + 0.5) % 1.0 - 0.5


def bin_phase(
    phase: np.ndarray, y: np.ndarray, n_bins: int = 25
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Mean of y in equal-width phase bins.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        phase: Phases in [-0.5, 0.5).
        y: Values to bin.
        n_bins: Number of bins.

    Returns:
        Tuple (bin centers, bin means, standard errors). Empty bins
        are NaN.
    """
    edges = np.linspace(-0.5, 0.5, n_bins + 1)
    idx = np.clip(np.digitize(phase, edges) - 1, 0, n_bins - 1)
    count = np.bincount(idx, minlength=n_bins).astype(float)
    total = np.bincount(idx, weights=y, minlength=n_bins)
    total2 = np.bincount(idx, weights=y * y, minlength=n_bins)
    with np.errstate(invalid="ignore", divide="ignore"):
        mean = total / count
        var = total2 / count - mean**2
        err = np.sqrt(np.clip(var, 0, None) / count)
    return 0.5 * (edges[1:] + edges[:-1]), mean, err


