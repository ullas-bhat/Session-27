def paczynski(
    t: np.ndarray, t0: float, tE: float, u0: float
) -> np.ndarray:
    """Point-source point-lens magnification A(t).

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        t0: Time of closest approach in days.
        tE: Einstein timescale in days.
        u0: Impact parameter in Einstein radii.

    Returns:
        Magnification, which tends to 1 far from the event.
    """
    u2 = u0**2 + ((t - t0) / tE) ** 2
    return (u2 + 2.0) / np.sqrt(u2 * (u2 + 4.0))


def ulens_template(
    t: np.ndarray, t0: float, t_eff: float, j: int
) -> np.ndarray:
    """Two-parameter microlensing template of Kim et al. (2018).

    Q = 1 + ((t - t0) / t_eff)^2, where t_eff = u0 * tE. The j = 0
    template is the high-magnification limit (u0 -> 0); j = 1 is
    the Paczynski curve with u0 = 1. Source and blend flux are
    linear and are fit separately: F = f_s * A_j + f_b.
    https://scixplorer.org/abs/2018AJ....155...76K/abstract

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        t0: Time of peak in days.
        t_eff: Effective timescale u0 * tE in days.
        j: 0 (high magnification) or 1 (u0 = 1).

    Returns:
        Template A_j(t).
    """
    q = 1.0 + ((t - t0) / t_eff) ** 2
    if j == 0:
        return q**-0.5
    return (q + 2.0) / np.sqrt(q * (q + 4.0))


def _ulens_times(rng: np.random.Generator) -> np.ndarray:
    """Irregular epochs: two observing seasons with weather losses.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        rng: Random generator.

    Returns:
        Sorted epochs in days.
    """
    seasons = [(0.0, 240.0), (365.0, 605.0)]
    times = []
    for lo, hi in seasons:
        nights = np.arange(lo, hi)
        nights = nights[rng.random(nights.size) > 0.35]
        for night in nights:
            n_obs = rng.integers(1, 4)
            times.append(night + 0.35 * rng.random(n_obs))
    return np.sort(np.concatenate(times))


def _roman_times() -> np.ndarray:
    """Epochs for two high-cadence Roman GBTDS seasons.

    Two 72 day seasons of F146 imaging every 12.1 minutes, starting
    half a year apart, which leaves a gap of about 110 days.
    https://roman-docs.stsci.edu/roman-community-defined-surveys/galactic-bulge-time-domain-survey

    Generated by Claude Fable 5.2 on November 16 2026.

    Returns:
        Sorted epochs in days, from the start of the first season.
    """
    cadence = 12.1 / 1440.0
    season = np.arange(0.0, 72.0, cadence)
    return np.concatenate([season, 182.6 + season])


def bin_lc(
    t: np.ndarray, flux: np.ndarray, width: float = 1.0
) -> tuple[np.ndarray, np.ndarray]:
    """Average a light curve in time bins of equal width.

    Generated by Claude Fable 5.2 on November 16 2026.

    Args:
        t: Times in days.
        flux: Flux at each time.
        width: Bin width in days.

    Returns:
        Tuple (t_bin, flux_bin): the mean time and mean flux of each
        bin that contains data.
    """
    idx = np.floor((t - t.min()) / width).astype(int)
    t_bin, flux_bin = [], []
    for k in np.unique(idx):
        t_bin.append(np.mean(t[idx == k]))
        flux_bin.append(np.mean(flux[idx == k]))
    return np.array(t_bin), np.array(flux_bin)


def make_ulens_lc(
    inject: bool = True,
    t0: float = 40.0,
    tE: float = 20.0,
    u0: float = 0.5,
    f_s: float = 0.02,
    f_b: float = 0.98,
    sigma: float = 0.05,
    seed: int = 11,
    survey: str = "roman",
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """One blended microlensing light curve.

    By default this mimics the first two high-cadence seasons of the
    Roman Galactic Bulge Time Domain Survey: two 72 day seasons at a
    12.1 minute cadence, about 110 days apart, with equal error bars.
    The default noise of 5% per exposure is roughly that of a faint
    (F146 ~ 23) source, and the source is heavily blended.

    With survey="ground" it returns the earlier ground-based stand-in:
    two 240 day seasons, irregular sampling, and unequal error bars
    (median 3%; `sigma` is ignored).

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        inject: If True, include the event. Otherwise flat.
        t0: Time of peak in days.
        tE: Einstein timescale in days.
        u0: Impact parameter.
        f_s: Source flux.
        f_b: Blend flux.
        sigma: Per-exposure flux uncertainty (Roman only).
        seed: Random seed.
        survey: "roman" or "ground".

    Returns:
        Tuple (t, flux, flux_err).
    """
    rng = np.random.default_rng(seed)
    if survey == "ground":
        t = _ulens_times(rng)
        err = 0.03 * np.exp(rng.normal(0.0, 0.5, t.size))
    else:
        t = _roman_times()
        err = np.full(t.size, sigma)
    mag = paczynski(t, t0, tE, u0) if inject else np.ones(t.size)
    flux = f_s * mag + f_b + rng.normal(0.0, err)
    return t, flux, err


def replay(seed: int = 3) -> Iterator[tuple[int, float, float, float]]:
    """Yield five simulated light curves one epoch at a time.

    For Challenge B. The five sources are, in some order, two
    microlensing events, a flare, a long-period variable, and a flat
    star. Epochs arrive in time order across all sources.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        seed: Random seed.

    Yields:
        Tuples (source_id, t, flux, flux_err).
    """
    rng = np.random.default_rng(seed)
    t = _ulens_times(rng)
    t = t[t < 240.0]
    order = rng.permutation(5)
    rows = []
    for sid, kind in zip(order, range(5)):
        tk = t[rng.random(t.size) > 0.3]
        err = 0.03 * np.exp(rng.normal(0.0, 0.4, tk.size))
        if kind == 0:
            model = 0.3 * paczynski(tk, 150.0, 25.0, 0.3) + 0.7
        elif kind == 1:
            model = 0.6 * paczynski(tk, 95.0, 8.0, 0.6) + 0.4
        elif kind == 2:
            dt = np.clip(tk - 120.2, 0.0, None)
            model = 1.0 + 0.8 * np.exp(-dt / 0.15) * (dt > 0)
        elif kind == 3:
            model = 1.0 + 0.15 * np.sin(2 * np.pi * tk / 310.0 + 4.0)
        else:
            model = np.ones(tk.size)
        flux = model + rng.normal(0.0, err)
        rows += [(int(sid), a, b, c) for a, b, c in zip(tk, flux, err)]
    rows.sort(key=lambda row: row[1])
    for row in rows:
        yield row


