def phase_bin(
    t: np.ndarray, flux: np.ndarray, period: float, n_bins: int = 200
) -> tuple[np.ndarray, np.ndarray]:
    """Fold a light curve and average it in bins of phase.

    Generated by Claude Fable 5.2 on November 16 2026.

    Args:
        t: Times in days.
        flux: Flux at each time.
        period: Period to fold on, in days.
        n_bins: Number of phase bins between 0 and 1.

    Returns:
        Tuple (phase_bin, flux_bin): the central phase and mean flux
        of each bin that contains data.
    """
    phase = (t / period) % 1.0
    idx = np.minimum((phase * n_bins).astype(int), n_bins - 1)
    count = np.bincount(idx, minlength=n_bins)
    total = np.bincount(idx, weights=flux, minlength=n_bins)
    keep = count > 0
    mid = (np.arange(n_bins) + 0.5) / n_bins
    return mid[keep], total[keep] / count[keep]


def plot_folded(
    ax, t: np.ndarray, flux: np.ndarray, period: float, n_bins: int = 200
) -> None:
    """Plot a phase-folded light curve on a matplotlib axis.

    The raw points are drawn in light gray, and the light curve
    averaged in `n_bins` phase bins is drawn over them in black. The
    y-range is set from the raw points, ignoring the most extreme 1%
    (flares, for example).

    Generated by Claude Fable 5.2 on November 16 2026.

    Args:
        ax: Matplotlib axis to draw on.
        t: Times in days.
        flux: Flux at each time.
        period: Period to fold on, in days.
        n_bins: Number of phase bins between 0 and 1.
    """
    phase = (t / period) % 1.0
    ax.plot(phase, flux, ".", c="0.75", ms=1, rasterized=True)
    p_bin, f_bin = phase_bin(t, flux, period, n_bins)
    ax.plot(p_bin, f_bin, "k.", ms=3)
    lo, hi = np.percentile(flux, [0.5, 99.5])
    pad = 0.15 * (hi - lo)
    ax.set_ylim(lo - pad, hi + pad)
    ax.set_xlim(0, 1)


def save_scocen_npz(
    path: str,
    ticids: np.ndarray,
    times: list[np.ndarray],
    fluxes: list[np.ndarray],
) -> None:
    """Write light curves in the format load_scocen_lcs() expects.

    Arrays are concatenated and stored with the number of points per
    star, so no pickling is needed.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        path: Output .npz path.
        ticids: TIC identifiers, one per star.
        times: Per-star time arrays in days (e.g. BTJD).
        fluxes: Per-star relative flux arrays, median near 1, with
            NaNs and bad-quality cadences already removed.
    """
    n_points = np.array([len(x) for x in times])
    np.savez_compressed(
        path,
        ticid=np.asarray(ticids, dtype=np.int64),
        n_points=n_points,
        time=np.concatenate(times).astype(np.float64),
        flux=np.concatenate(fluxes).astype(np.float32),
    )


def load_scocen_lcs(
    path: str = SCOCEN_PATH,
) -> tuple[np.ndarray, list[np.ndarray], list[np.ndarray]]:
    """Load the Sco-Cen TESS 2-minute light curves for Problem 4.

    If `path` (the full sample, 330 MB, downloaded separately) is
    missing, loads the 300-star subsample at SCOCEN_SUB_PATH.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        path: Path to the .npz file written by save_scocen_npz().

    Returns:
        Tuple (ticids, times, fluxes). `times` and `fluxes` are
        lists with one array per star.

    Raises:
        FileNotFoundError: If neither file exists.
    """
    if not os.path.exists(path) and os.path.exists(SCOCEN_SUB_PATH):
        print(
            f"{os.path.basename(path)} not found: loading the "
            "300-star subsample."
        )
        path = SCOCEN_SUB_PATH
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Found neither {path} nor {SCOCEN_SUB_PATH}. Download "
            "one of them (links in data/README.md) and put it in "
            f"{os.path.dirname(SCOCEN_SUB_PATH)}."
        )
    with np.load(path) as f:
        ticids = f["ticid"]
        splits = np.cumsum(f["n_points"])[:-1]
        times = np.split(f["time"], splits)
        fluxes = np.split(f["flux"].astype(np.float64), splits)
    return ticids, times, fluxes

