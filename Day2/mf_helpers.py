def box_model(
    t: np.ndarray, period: float, t0: float, duration: float
) -> np.ndarray:
    """Boolean in-transit mask for a periodic box.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        period: Orbital period in days.
        t0: Mid-transit time in days.
        duration: Transit duration in days.

    Returns:
        Boolean array, True in transit.
    """
    phase = (t - t0 + 0.5 * period) % period - 0.5 * period
    return np.abs(phase) < 0.5 * duration


def inject_transit(
    t: np.ndarray,
    flux: np.ndarray,
    period: float,
    t0: float,
    duration: float,
    depth: float,
) -> np.ndarray:
    """Subtract a box transit from a light curve.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        t: Times in days.
        flux: Relative flux.
        period: Orbital period in days.
        t0: Mid-transit time in days.
        duration: Transit duration in days.
        depth: Transit depth in relative flux.

    Returns:
        New flux array with the transit injected.
    """
    return flux - depth * box_model(t, period, t0, duration)


def make_transit_lc(
    inject: bool = True,
    period: float = 3.7,
    t0: float = 1.3,
    duration: float = 0.125,
    depth: float = 9.0e-4,
    sigma: float = 6.0e-4,
    realistic: bool = True,
    seed: int = 3,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """One 27 day, 30 minute cadence light curve.

    Mimics one TESS sector: a data gap at mid-sector, white noise,
    and (if `realistic`) low-level red noise and a few glitches. The
    reported uncertainties describe only the white noise.

    Generated by Claude Fable 5.2 on November 13 2026.

    Args:
        inject: If True, inject one box-shaped planet.
        period: Orbital period in days.
        t0: Mid-transit time in days.
        duration: Transit duration in days.
        depth: Transit depth in relative flux.
        sigma: White-noise standard deviation per cadence.
        realistic: If True, add red noise and glitches.
        seed: Random seed.

    Returns:
        Tuple (t, flux, flux_err), with flux normalized to 1.
    """
    rng = np.random.default_rng(seed)
    t = np.arange(0.0, 27.0, 1.0 / 48.0)
    t = t[(t < 12.6) | (t > 14.1)]
    n = t.size
    flux = 1.0 + rng.normal(0.0, sigma, n)
    if realistic:
        # red noise: AR(1), correlation time about 3 hours
        phi = 0.85
        kick = rng.normal(0.0, 1.0, n)
        red = np.zeros(n)
        for i in range(1, n):
            red[i] = phi * red[i - 1] + kick[i]
        flux += 0.3 * sigma * red / np.std(red)
        # glitches: short excursions of both signs
        g_t = np.array([4.9, 9.2, 16.8, 21.4, 24.3])
        g_a = np.array([-2.6, 3.0, 2.4, -2.2, 2.8]) * sigma
        g_w = np.array([0.06, 0.07, 0.05, 0.07, 0.06])
        for gt, ga, gw in zip(g_t, g_a, g_w):
            flux += ga * (np.abs(t - gt) < 0.5 * gw)
    if inject:
        flux = inject_transit(t, flux, period, t0, duration, depth)
    return t, flux, np.full(n, sigma)


